# Installs/starts SubscriptionsAPI + SubscriptionsWeb under PM2 on the CLIENT server.
# - npm install -g pm2 (if missing)
# - pm2 start ecosystem.config.cjs
# - pm2 save
# - pm2 startup (+ Windows Scheduled Task fallback for boot resurrect)
# Does NOT touch any SQL database.

[CmdletBinding()]
param(
  [Parameter(Mandatory = $true)]
  [string]$RepoRoot,
  [string]$PackageRoot,
  [switch]$ForceRestart
)

# Native npm/node write warnings to stderr; keep non-terminating for those calls.
$ErrorActionPreference = 'Continue'
$PSNativeCommandUseErrorActionPreference = $false

if ([string]::IsNullOrWhiteSpace($PackageRoot)) {
  $PackageRoot = Split-Path -Parent $PSScriptRoot
}
$RepoRoot = (Resolve-Path -LiteralPath $RepoRoot).Path
$PackageRoot = (Resolve-Path -LiteralPath $PackageRoot).Path

$ApiName = 'SubscriptionsAPI'
$WebName = 'SubscriptionsWeb'
$EcoPath = Join-Path $PackageRoot 'ecosystem.config.cjs'
$BootTaskName = 'SubscriptionsPM2-Resurrect'

function Refresh-Path {
  $env:Path = [System.Environment]::GetEnvironmentVariable('Path', 'Machine') + ';' +
              [System.Environment]::GetEnvironmentVariable('Path', 'User')
}

function Test-IsAdmin {
  $p = [Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()
  return $p.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

function Get-Pm2Cmd {
  Refresh-Path
  $cmd = Get-Command pm2.cmd -ErrorAction SilentlyContinue
  if (-not $cmd) { $cmd = Get-Command pm2 -ErrorAction SilentlyContinue }
  if ($cmd) { return $cmd.Source }
  $candidates = @(
    (Join-Path $env:APPDATA 'npm\pm2.cmd'),
    (Join-Path $env:ProgramFiles 'nodejs\pm2.cmd'),
    'C:\Program Files\nodejs\pm2.cmd'
  )
  foreach ($c in $candidates) {
    if ($c -and (Test-Path -LiteralPath $c)) { return $c }
  }
  return $null
}

function Invoke-Pm2 {
  param([Parameter(ValueFromRemainingArguments = $true)][string[]]$Pm2Args)
  $pm2 = Get-Pm2Cmd
  if (-not $pm2) { throw 'pm2 not found on PATH after install.' }
  $prev = $ErrorActionPreference
  $ErrorActionPreference = 'Continue'
  try {
    # Prefer pm2.cmd via cmd so Node stderr does not become terminating errors
    $argLine = ($Pm2Args | ForEach-Object {
      if ($_ -match '[\s"]') { '"' + ($_ -replace '"', '\"') + '"' } else { $_ }
    }) -join ' '
    cmd /c "`"$pm2`" $argLine"
    return $LASTEXITCODE
  } finally {
    $ErrorActionPreference = $prev
  }
}

function Ensure-Pm2Global {
  Refresh-Path
  if (Get-Pm2Cmd) {
    Write-Host "PM2 present: $(Get-Pm2Cmd)" -ForegroundColor Green
    cmd /c "pm2 -v" | Out-Host
    return
  }
  Write-Host 'Installing PM2 globally (npm install -g pm2)...' -ForegroundColor Cyan
  # npm writes warnings to stderr; do not treat as terminating under $ErrorActionPreference Stop
  $prev = $ErrorActionPreference
  $ErrorActionPreference = 'Continue'
  try {
    cmd /c "npm install -g pm2"
    $code = $LASTEXITCODE
  } finally {
    $ErrorActionPreference = $prev
  }
  if ($code -ne 0) { throw "npm install -g pm2 failed (exit $code)" }
  Refresh-Path
  if (-not (Get-Pm2Cmd)) {
    throw 'PM2 installed but not on PATH in this session. Open a new shell and re-run Install-Pm2Processes.ps1.'
  }
  Write-Host "PM2 ready: $(Get-Pm2Cmd)" -ForegroundColor Green
}

function Stop-ConflictingListeners {
  foreach ($name in @($ApiName, $WebName)) {
    $svc = Get-Service -Name $name -ErrorAction SilentlyContinue
    if ($svc) {
      Write-Host "Stopping legacy WinSW service $name (PM2 takes over)..." -ForegroundColor Yellow
      Stop-Service -Name $name -Force -ErrorAction SilentlyContinue
    }
  }
  foreach ($port in @(5050, 5173)) {
    Get-NetTCPConnection -LocalPort $port -State Listen -ErrorAction SilentlyContinue | ForEach-Object {
      if ($_.OwningProcess -gt 0) {
        Write-Host "Freeing TCP $port (PID $($_.OwningProcess))..." -ForegroundColor Yellow
        Stop-Process -Id $_.OwningProcess -Force -ErrorAction SilentlyContinue
      }
    }
  }
  Start-Sleep -Seconds 1
}

function Write-EcosystemFile {
  $serverDir = (Join-Path $RepoRoot 'server') -replace '\\', '/'
  $webDir = (Join-Path $RepoRoot 'web') -replace '\\', '/'
  $viteRel = 'node_modules/vite/bin/vite.js'
  $viteAbs = Join-Path $RepoRoot "web\$($viteRel -replace '/', '\')"
  if (-not (Test-Path -LiteralPath (Join-Path $RepoRoot 'server\src\index.js'))) {
    throw "Missing server entry: $RepoRoot\server\src\index.js"
  }
  if (-not (Test-Path -LiteralPath $viteAbs)) {
    throw "Missing Vite at $viteAbs — run npm install in web first."
  }

  # Keep NODE_ENV unset/development so LAN http:// cookies are not Secure-only.
  $content = @"
/** Generated by Install-Pm2Processes.ps1 — do not point at a DB; runtime uses server/.env */
module.exports = {
  apps: [
    {
      name: '$ApiName',
      cwd: '$serverDir',
      script: 'src/index.js',
      interpreter: 'node',
      instances: 1,
      exec_mode: 'fork',
      autorestart: true,
      watch: false,
      max_restarts: 40,
      min_uptime: '5s',
      time: true
    },
    {
      name: '$WebName',
      cwd: '$webDir',
      script: '$viteRel',
      args: '--host 0.0.0.0 --port 5173',
      interpreter: 'node',
      instances: 1,
      exec_mode: 'fork',
      autorestart: true,
      watch: false,
      max_restarts: 40,
      min_uptime: '5s',
      time: true
    }
  ]
};
"@
  Set-Content -LiteralPath $EcoPath -Value $content -Encoding UTF8
  Write-Host "Wrote $EcoPath" -ForegroundColor DarkGray
}

function Ensure-WindowsBootTask {
  # Native `pm2 startup` is Linux/systemd-oriented ("Init system not found" on Windows).
  # Persist via: (1) current-user Startup folder script (2) Scheduled Task when allowed.
  $pm2 = Get-Pm2Cmd
  if (-not $pm2) { return }

  $startupDir = Join-Path $env:APPDATA 'Microsoft\Windows\Start Menu\Programs\Startup'
  New-Item -ItemType Directory -Force -Path $startupDir | Out-Null
  $startupCmd = Join-Path $startupDir 'SubscriptionsPM2-Resurrect.cmd'
  $cmdBody = @"
@echo off
REM Auto-generated by Install-Pm2Processes.ps1 — resurrects PM2 apps after logon/reboot
"$pm2" resurrect
"@
  Set-Content -LiteralPath $startupCmd -Value $cmdBody -Encoding ASCII
  Write-Host "Startup folder hook: $startupCmd" -ForegroundColor Green

  $tr = "cmd.exe /c `"\`"$pm2\`" resurrect`""
  schtasks.exe /Delete /TN $BootTaskName /F 2>$null | Out-Null
  if (Test-IsAdmin) {
    $user = "$env:USERDOMAIN\$env:USERNAME"
    schtasks.exe /Create /TN $BootTaskName /SC ONSTART /DELAY 0001:00 /RL HIGHEST /RU $user /IT /F /TR $tr 2>$null | Out-Null
    if ($LASTEXITCODE -eq 0) {
      Write-Host "Boot task registered (ONSTART): $BootTaskName" -ForegroundColor Green
      return
    }
  }
  # Current-user logon task (no password / no Admin in many environments)
  schtasks.exe /Create /TN $BootTaskName /SC ONLOGON /F /TR $tr 2>$null | Out-Null
  if ($LASTEXITCODE -eq 0) {
    Write-Host "Logon task registered: $BootTaskName -> pm2 resurrect" -ForegroundColor Green
  } else {
    Write-Host "Scheduled Task not created (Access denied). Startup folder hook is still active for this user." -ForegroundColor Yellow
    Write-Host 'For machine-wide boot: re-run Install-Pm2Processes.ps1 as Administrator once.' -ForegroundColor Yellow
  }
}

function Invoke-Pm2StartupHook {
  Write-Host 'Configuring pm2 startup / Windows boot resurrect...' -ForegroundColor Cyan
  # Official CLI — expected to fail on Windows with "Init system not found"; still attempt + save.
  # Redirect all streams so Windows "Init system not found" does not surface as a terminating error
  $tmpOut = Join-Path $env:TEMP 'pm2-startup-out.txt'
  cmd /c "pm2 startup > `"$tmpOut`" 2>&1"
  $out = if (Test-Path -LiteralPath $tmpOut) { Get-Content -LiteralPath $tmpOut -Raw } else { '' }
  if ($out -match 'Init system not found') {
    Write-Host 'pm2 startup: no Linux init on Windows — using Startup folder + Scheduled Task instead.' -ForegroundColor DarkYellow
  } elseif ($out.Trim()) {
    Write-Host $out
  }
  $winStartup = Get-Command pm2-startup -ErrorAction SilentlyContinue
  if ($winStartup) {
    Write-Host 'Running pm2-startup install...' -ForegroundColor Cyan
    cmd /c "pm2-startup install" 2>&1 | Out-Host
  }
  Ensure-WindowsBootTask
  # Always re-save after startup hooks
  Invoke-Pm2 save | Out-Null
}

# --- main ---
Write-Host ''
Write-Host '=== PM2: SubscriptionsAPI (:5050) + SubscriptionsWeb (:5173) ===' -ForegroundColor Cyan
Write-Host "Repo: $RepoRoot"

if (-not (Get-Command node -ErrorAction SilentlyContinue) -or -not (Get-Command npm -ErrorAction SilentlyContinue)) {
  throw 'Node.js/npm required on PATH before PM2 setup.'
}

Ensure-Pm2Global
Write-EcosystemFile
Stop-ConflictingListeners

# Remove prior PM2 apps with same names (idempotent reinstall)
foreach ($n in @($ApiName, $WebName)) {
  Invoke-Pm2 delete $n 2>$null | Out-Null
}

Write-Host "Starting apps from ecosystem: $EcoPath" -ForegroundColor Cyan
$startCode = Invoke-Pm2 start $EcoPath
if ($startCode -ne 0 -and $null -ne $startCode) {
  # pm2 sometimes returns null; verify with list
}
Invoke-Pm2 status | Out-Host

Write-Host 'Saving PM2 process list (pm2 save)...' -ForegroundColor Cyan
Invoke-Pm2 save | Out-Host

Invoke-Pm2StartupHook

Write-Host ''
Write-Host 'PM2 processes:' -ForegroundColor Green
Invoke-Pm2 status | Out-Host
Write-Host ''
Write-Host 'Manage with:' -ForegroundColor Cyan
Write-Host '  pm2 status'
Write-Host '  pm2 logs SubscriptionsAPI'
Write-Host '  pm2 logs SubscriptionsWeb'
Write-Host '  pm2 restart all'
Write-Host '  pm2 stop all'
Write-Host '  pm2 save'
Write-Host ''
Write-Host 'Survives terminal close via PM2 daemon. Boot: pm2 startup + task SubscriptionsPM2-Resurrect (pm2 resurrect).' -ForegroundColor DarkYellow
Write-Host 'No database changes were made.' -ForegroundColor DarkGray
